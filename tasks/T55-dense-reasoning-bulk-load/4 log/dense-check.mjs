import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import assert from 'node:assert/strict';
const modulePath = process.argv[2];
const { IncrementalEvaluator } = await import(pathToFileURL(modulePath).href);
const { evaluate } = await import(pathToFileURL(join(dirname(modulePath), 'engine.js')).href);
const instance = JSON.parse(readFileSync(process.argv[3], 'utf8'));
const framework = instance.framework;
const start = performance.now();
const incremental = new IncrementalEvaluator(framework);
const buildMs = performance.now() - start;
assert.deepEqual(incremental.evaluate().labels, evaluate(framework).labels);
const [from, to] = framework.attacks[0];
const editStart = performance.now();
incremental.removeAttack(from, to);
const editMs = performance.now() - editStart;
const edited = { args: framework.args, attacks: framework.attacks.filter(([a, b]) => a !== from || b !== to) };
assert.deepEqual(incremental.evaluate().labels, evaluate(edited).labels);
console.log(JSON.stringify({ id: instance.id, args: framework.args.length, attacks: framework.attacks.length, buildMs, editMs, sameBefore: true, sameAfter: true }));
